#!/usr/bin/env bash
#
# aggregate_ci_results.sh — Read /tmp/ci-results/*.jsonl and produce
# docs/testing/CI_MATRIX_REPORT.md
#
# Each line in the .jsonl files is one of:
#   {"script":"tests/xxx_ci.sh","status":"PASS","exit_code":0,"duration_s":12,"log_path":"/tmp/..."}
#   {"script":"tests/yyy_ci.sh","status":"FAIL","exit_code":1,"duration_s":5,"log_path":"/tmp/..."}
#   {"script":"tests/zzz_ci.sh","status":"SKIP","reason":"env-dependent","exit_code":-1,"duration_s":0}
#
set -o pipefail
# NOTE: not using `set -u` — macOS bash 3.2 chokes on possibly-unbound vars in arithmetic.

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
RESULTS_DIR="/tmp/ci-results"
REPORT="$PROJECT_DIR/docs/testing/CI_MATRIX_REPORT.md"

mkdir -p "$(dirname "$REPORT")"

if [ ! -d "$RESULTS_DIR" ] || [ -z "$(ls -A "$RESULTS_DIR" 2>/dev/null)" ]; then
    echo "❌ No results found in $RESULTS_DIR"
    exit 1
fi

# ─── Collect all result lines (dedup by script — keep last result) ────────
TMP_JSONL="/tmp/ci-aggregate.jsonl"
cat "$RESULTS_DIR"/*.jsonl 2>/dev/null | python3 -c "
import json, sys
results = {}
for line in sys.stdin:
    line = line.strip()
    if not line: continue
    try:
        d = json.loads(line)
        results[d['script']] = d  # last result wins
    except: pass
for d in results.values():
    print(json.dumps(d))
" > "$TMP_JSONL" 2>/dev/null
TOTAL_LINES=$(wc -l < "$TMP_JSONL" | tr -d ' ')

if [ "$TOTAL_LINES" -eq 0 ]; then
    echo "❌ No result lines in $RESULTS_DIR/*.jsonl"
    exit 1
fi

# ─── Tally counts ──────────────────────────────────────────────────────────
PASS_COUNT=$(grep -c '"status":"PASS"' "$TMP_JSONL" 2>/dev/null || true)
FAIL_COUNT=$(grep -c '"status":"FAIL"' "$TMP_JSONL" 2>/dev/null || true)
SKIP_COUNT=$(grep -c '"status":"SKIP"' "$TMP_JSONL" 2>/dev/null || true)
# Defend against empty (grep -c returns "0" but `|| true` may yield "")
PASS_COUNT=${PASS_COUNT:-0}
FAIL_COUNT=${FAIL_COUNT:-0}
SKIP_COUNT=${SKIP_COUNT:-0}
TOTAL=$((PASS_COUNT + FAIL_COUNT + SKIP_COUNT))

# ─── Generate report ───────────────────────────────────────────────────────
{
    echo "# CI Matrix Report"
    echo ""
    echo "> Auto-generated by \`scripts/aggregate_ci_results.sh\`"
    echo "> Run: \`bash scripts/run_ci_matrix.sh\`"
    echo "> Date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo ""
    echo "## Summary"
    echo ""
    echo "| Status | Count |"
    echo "|--------|-------|"
    echo "| ✅ PASS | $PASS_COUNT |"
    echo "| ❌ FAIL | $FAIL_COUNT |"
    echo "| ⏭️ SKIP | $SKIP_COUNT |"
    echo "| **Total** | **$TOTAL** |"
    echo ""
    if [ "$FAIL_COUNT" -gt 0 ]; then
        PASS_PCT=$(awk "BEGIN { printf \"%.1f\", ($PASS_COUNT / $TOTAL) * 100 }")
        echo "Pass rate: **${PASS_PCT}%**"
        echo ""
    fi

    # ─── FAIL details ──────────────────────────────────────────────────────
    if [ "$FAIL_COUNT" -gt 0 ]; then
        echo "## ❌ Failed Scripts"
        echo ""
        echo "| Script | Exit | Duration | Log |"
        echo "|--------|------|----------|-----|"
        grep '"status":"FAIL"' "$TMP_JSONL" | while IFS= read -r line; do
            SCRIPT=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read())['script'])" 2>/dev/null)
            EXIT=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('exit_code','?'))" 2>/dev/null)
            DUR=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('duration_s','?'))" 2>/dev/null)
            LOG=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('log_path','-'))" 2>/dev/null)
            BASENAME=$(basename "$SCRIPT" .sh)
            echo "| \`$SCRIPT\` | $EXIT | ${DUR}s | [$BASENAME]($LOG) |"
        done
        echo ""

        # ─── Error excerpts (last 20 lines per failed script) ──────────────
        echo "## Error Excerpts"
        echo ""
        echo "<details><summary>Click to expand failure logs</summary>"
        echo ""
        grep '"status":"FAIL"' "$TMP_JSONL" | while IFS= read -r line; do
            SCRIPT=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read())['script'])" 2>/dev/null)
            LOG=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('log_path',''))" 2>/dev/null)
            echo "### $SCRIPT"
            echo ""
            if [ -f "$LOG" ]; then
                echo '```'
                tail -20 "$LOG" 2>/dev/null
                echo '```'
            else
                echo "(log file not found: $LOG)"
            fi
            echo ""
        done
        echo "</details>"
        echo ""
    fi

    # ─── SKIP details ──────────────────────────────────────────────────────
    if [ "$SKIP_COUNT" -gt 0 ]; then
        echo "## ⏭️ Skipped Scripts"
        echo ""
        echo "| Script | Reason |"
        echo "|--------|--------|"
        grep '"status":"SKIP"' "$TMP_JSONL" | while IFS= read -r line; do
            SCRIPT=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read())['script'])" 2>/dev/null)
            REASON=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('reason','unknown'))" 2>/dev/null)
            echo "| \`$SCRIPT\` | $REASON |"
        done
        echo ""
    fi

    # ─── PASS list (collapsed) ─────────────────────────────────────────────
    if [ "$PASS_COUNT" -gt 0 ]; then
        echo "## ✅ Passed Scripts"
        echo ""
        echo "<details><summary>$PASS_COUNT scripts passed — click to expand</summary>"
        echo ""
        grep '"status":"PASS"' "$TMP_JSONL" | while IFS= read -r line; do
            SCRIPT=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read())['script'])" 2>/dev/null)
            DUR=$(echo "$line" | python3 -c "import json,sys; print(json.loads(sys.stdin.read()).get('duration_s','?'))" 2>/dev/null)
            echo "- \`$SCRIPT\` (${DUR}s)"
        done
        echo ""
        echo "</details>"
        echo ""
    fi

    echo "---"
    echo ""
    echo "## Next Steps"
    echo ""
    if [ "$FAIL_COUNT" -eq 0 ]; then
        echo "All runnable scripts passed ✅"
    else
        echo "For each FAIL above:"
        echo "1. ZCode reads the log excerpt to determine root cause."
        echo "2. If the failure is a **script bug** (not env / not product code):"
        echo "   ZCode launches \`ion --host --agent developer\` to fix it in a worktree."
        echo "3. If the failure is **environment-dependent** (missing API key, service, runtime):"
        echo "   Mark as \`SKIP\` with the reason — not a real failure."
        echo "4. If the failure reveals a **product code bug**: record separately, do not fix in this run."
    fi

} > "$REPORT"

echo "✅ Report written to: $REPORT"
echo ""
echo "Quick stats:"
echo "  PASS: $PASS_COUNT"
echo "  FAIL: $FAIL_COUNT"
echo "  SKIP: $SKIP_COUNT"
echo "  Total: $TOTAL"
